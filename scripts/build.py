"""Rebuild the whole profile from docs/profile.json (+ your GitHub avatar and contributions).

    python scripts/build.py            # everything, like the daily GitHub Action
    python scripts/build.py --offline  # skip the downloads, redraw from what is here

Order matters: the profile is checked FIRST, so a mistake in profile.json stops the
build before anything is drawn. The Action only commits when this script succeeds,
so a broken edit never reaches the live profile; it keeps the last good version and
the failed run's log says exactly what to fix.
"""

import html
import io
import json
import os
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from profile import ProfileError, load  # noqa: E402
from theme import ROOT  # noqa: E402

PAGES = "https://mdyounus-git.github.io/mdyounus-git/"
REPO = "https://github.com/mdyounus-git/mdyounus-git"
IN_ACTIONS = os.environ.get("GITHUB_ACTIONS") == "true"


def warn(msg):
    print(f"::warning::{msg}" if IN_ACTIONS else f"WARNING: {msg}")


def fail(msg):
    if IN_ACTIONS:
        print("::error title=Profile not updated::" + msg.replace("\n", "%0A"))
    print(msg)
    print("\nNothing was changed on the live profile; fix the above and save again.")
    sys.exit(1)


def sync_avatar(user):
    """Fetch the current GitHub avatar; keep the old one if anything goes wrong."""
    import requests
    from PIL import Image

    from make_ascii_svg import flatten
    dst = ROOT / "scripts" / "source-avatar.jpg"
    try:
        r = requests.get(f"https://github.com/{user}.png?size=460", timeout=30)
        r.raise_for_status()
        img = Image.open(io.BytesIO(r.content))
        img.seek(0)  # first frame of an animated GIF
        img = flatten(img)  # transparency, palette, 16-bit... -> plain RGB with the subject kept
    except Exception as e:  # network, 404, not an image...
        warn(f"could not download the avatar ({e}); keeping the current portrait")
        return
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=92)
    if not dst.exists() or dst.read_bytes() != buf.getvalue():
        dst.write_bytes(buf.getvalue())
        print("avatar changed: portrait will be redrawn")


def pages_live():
    """True only if the live terminal (GitHub Pages) really answers.

    Every block on the profile is a link. If they pointed at the Pages site while it
    is switched off or broken, each click would land on a 404. So the build checks
    the site first and links to the repo instead when it is down; the next run
    (every 3 hours) switches the links back as soon as the site works.
    """
    import requests
    try:
        r = requests.get(PAGES, timeout=20)
        return r.status_code == 200 and "<html" in r.text.lower()
    except Exception:
        return False


def make_link(live):
    """cmd -> where a click on that block goes: the live terminal, or the repo when it is down."""
    return (lambda cmd: f"{PAGES}?cmd={cmd}") if live else (lambda cmd: REPO)


def attr(s):
    return html.escape(str(s), quote=True)


def readme(p, radars, buttons, heatmap, link):
    """The profile README, generated so file names and links always match the art.

    Order: portrait + card, heatmap, toolbox, radars, then the buttons as a footer."""
    to_levels, to_neofetch, to_whoami = link("levels"), link("neofetch"), link("whoami")
    cells = "\n".join(
        f'    <td valign="top"><a href="{to_levels}"><img src="./radar-{key}.svg" width="430" '
        f'alt="{attr(spec["title"].split("/")[-1].replace(".radar", ""))} radar: '
        f'{attr(", ".join(f"{a[0]} {a[1]}" for a in spec["axes"]))}" /></a></td>'
        for key, spec in radars.items())
    radar_table = f"<table>\n  <tr>\n{cells}\n  </tr>\n</table>\n" if radars else ""
    # a button with no link yet stays on the profile instead of opening the button image
    home = "https://github.com/" + p["github"]
    btns = "\n".join(
        f'<a href="{attr(url or home)}"><img src="./{path}" height="40" alt="{attr(name)}" /></a>'
        for name, path, url in buttons)
    tb = p.get("toolbox")
    to_tools = attr(link("tools"))
    toolbox = (f'<a href="{to_tools}"><img src="./toolbox.svg" width="860" alt="{attr(tb["heading"])}: '
               f'{attr(", ".join(t for r in tb["rows"] for t in r["tools"]))}" /></a>\n' if tb else "")
    about = f'{p["name"]}, {p["role"]}: ' + ", ".join(p.get("interests", [])[:4])
    return f"""<!-- Generated by scripts/build.py. Edit docs/profile.json instead; this file is rewritten on every build. -->
<div align="center">

<table>
  <tr>
    <td valign="top"><a href="{to_neofetch}"><img src="./spider-ascii.svg" width="370" alt="ASCII-art portrait of the profile picture" /></a></td>
    <td valign="top"><a href="{to_whoami}"><img src="./info-card.svg" width="490" alt="{attr(about)}" /></a></td>
  </tr>
</table>
{heatmap}
{toolbox}{radar_table}
{btns}

</div>
"""


def check_svgs():
    bad = []
    for f in list(ROOT.glob("*.svg")) + list((ROOT / "buttons").glob("*.svg")) + list((ROOT / "hm").glob("*.svg")):
        try:
            ET.parse(f)
        except ET.ParseError as e:
            bad.append(f"{f.name}: {e}")
    if bad:
        fail("generated art is not valid SVG:\n" + "\n".join(bad))


def main():
    offline = "--offline" in sys.argv
    try:
        p = load()
    except ProfileError as e:
        fail(str(e))
    print(f"profile.json OK ({len(p['card'])} card rows, radars: {', '.join(p['radar']) or 'none'})")

    import fetch_contributions
    import make_ascii_svg
    import make_buttons
    import make_info_card
    import make_radar_svg
    import make_toolbox
    import render_heatmap_svg
    import render_heatmap_tiles

    if not offline:
        sync_avatar(p["github"])
    make_ascii_svg.main()

    if not offline:
        try:
            fetch_contributions.main()
        except Exception as e:
            warn(f"contributions not refreshed ({e}); the heatmap keeps the last good data")
    if not (ROOT / "data" / "contributions.json").exists():
        fail("data/contributions.json is missing; run once without --offline")
    render_heatmap_svg.main()
    live = (not offline) and pages_live()
    if not live:
        warn(f"the live terminal {PAGES} does not answer; profile links go to the repo instead of a 404")
    link = make_link(live)
    heatmap = render_heatmap_tiles.main(link("stats"))

    (ROOT / "info-card.svg").write_text(make_info_card.render(p), encoding="utf-8")
    print("wrote info-card.svg")

    keep = set()
    for key, spec in p["radar"].items():
        f = ROOT / f"radar-{key}.svg"
        f.write_text(make_radar_svg.radar(spec), encoding="utf-8")
        keep.add(f.name)
        print(f"wrote {f.name}")
    for old in ROOT.glob("radar-*.svg"):  # charts that were renamed or removed
        if old.name not in keep:
            old.unlink()
            print(f"removed {old.name}")

    if p.get("toolbox"):
        (ROOT / "toolbox.svg").write_text(make_toolbox.render(p), encoding="utf-8")
        print("wrote toolbox.svg")
    elif (ROOT / "toolbox.svg").exists():
        (ROOT / "toolbox.svg").unlink()

    buttons = make_buttons.render(p)
    print(f"wrote {len(buttons)} buttons: {', '.join(n for n, _, _ in buttons)}")

    (ROOT / "README.md").write_text(readme(p, p["radar"], buttons, heatmap, link), encoding="utf-8")
    # the live terminal reads this checked copy, never the file you are editing
    (ROOT / "docs" / "profile.live.json").write_text(json.dumps(p, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote README.md and docs/profile.live.json")

    check_svgs()
    print("build OK")


if __name__ == "__main__":
    main()
